            "quest_kanto_gym_2_misty" -> setOf("tl_kanto_7_cerulean_gym", "mist_fen", "cascade")
            "tl_kanto_11_vermilion_gym" -> setOf("quest_kanto_gym_3_lt_surge", "ancient_crag", "thunder")
            "quest_kanto_gym_3_lt_surge" -> setOf("tl_kanto_11_vermilion_gym", "ancient_crag", "thunder")
            "tl_kanto_14_celadon_gym" -> setOf("quest_kanto_gym_4_erika", "sacred_grove", "rainbow")
            "quest_kanto_gym_4_erika" -> setOf("tl_kanto_14_celadon_gym", "sacred_grove", "rainbow")
            "tl_kanto_18_fuchsia_gym" -> setOf("quest_kanto_gym_5_koga", "ember_spirit", "soul")
            "quest_kanto_gym_5_koga" -> setOf("tl_kanto_18_fuchsia_gym", "ember_spirit", "soul")
            "tl_kanto_20_saffron_gym" -> setOf("quest_kanto_gym_6_sabrina", "celestial_canopy", "marsh")
            "quest_kanto_gym_6_sabrina" -> setOf("tl_kanto_20_saffron_gym", "celestial_canopy", "marsh")
            "tl_kanto_23_cinnabar_gym" -> setOf("quest_kanto_gym_7_blaine", "astral_bloom", "volcano")
            "quest_kanto_gym_7_blaine" -> setOf("tl_kanto_23_cinnabar_gym", "astral_bloom", "volcano")
            "tl_kanto_24_viridian_gym" -> setOf("quest_kanto_gym_8_giovanni", "sovereign_wild", "earth")
            "quest_kanto_gym_8_giovanni" -> setOf("tl_kanto_24_viridian_gym", "sovereign_wild", "earth")
            "tl_kanto_30_champion" -> setOf("quest_kanto_champion", "quest_kanto_e4_4_lance", "league")
            "tl_johto_16_e4_lance" -> setOf("quest_johto_champion", "tl_johto_17_champion_red", "johto_crown")
            "tl_hoenn_16_champion" -> setOf("quest_hoenn_champion", "hoenn_crown")
            "tl_sinnoh_16_champion" -> setOf("quest_sinnoh_champion", "sinnoh_crown")
            "tl_sinnoh_3_oreburgh_gym" -> setOf("quest_sinnoh_gym_1_oreburgh", "coal")
            "tl_sinnoh_4_eterna_gym" -> setOf("quest_sinnoh_gym_2_eterna", "forest")
            "tl_sinnoh_5_veilstone_gym" -> setOf("quest_sinnoh_gym_3_veilstone", "cobble")
            "tl_sinnoh_6_pastoria_gym" -> setOf("quest_sinnoh_gym_4_pastoria", "fen")
            "tl_sinnoh_7_hearthome_gym" -> setOf("quest_sinnoh_gym_5_hearthome", "relic")
            "tl_sinnoh_8_canalave_gym" -> setOf("quest_sinnoh_gym_6_canalave", "mine")
