    fun isQuestCompleted(
        questId: String,
        completedSet: Set<String>,
        inventoryItemIds: Set<String> = emptySet(),
        bankItemIds: Set<String> = emptySet()
    ): Boolean {
        if (completedSet.contains(questId)) return true

        val aliases = when (questId) {
            "tl_kanto_4_pewter_gym" -> setOf("quest_kanto_gym_1_brock", "woodland", "boulder")
