            "tl_sinnoh_10_sunyshore_gym" -> setOf("quest_sinnoh_gym_8_sunyshore", "beacon")
            else -> emptySet()
        }
        if (aliases.any { completedSet.contains(it) }) return true

        val questObj = getQuestById(questId) ?: OsrsQuestData.ALL_QUESTS.find { it.id == questId }
        if (questObj?.rewardItemId != null) {
            val rId = questObj.rewardItemId
            if (inventoryItemIds.contains(rId) || bankItemIds.contains(rId)) return true
        }

        return false
    }

