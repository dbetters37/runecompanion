    }

    fun getRegionForQuest(questId: String): TrainerRegion? {
        return when {
            questId.startsWith("tl_kanto_") || questId.startsWith("quest_kanto_") -> TrainerRegion.KANTO
            questId.startsWith("tl_johto_") || questId.startsWith("quest_johto_") -> TrainerRegion.JOHTO
            questId.startsWith("tl_hoenn_") || questId.startsWith("quest_hoenn_") -> TrainerRegion.HOENN
            questId.startsWith("tl_sinnoh_") || questId.startsWith("quest_sinnoh_") -> TrainerRegion.SINNOH
            KANTO_QUESTS.any { it.id == questId } -> TrainerRegion.KANTO
            JOHTO_QUESTS.any { it.id == questId } -> TrainerRegion.JOHTO
            HOENN_QUESTS.any { it.id == questId } -> TrainerRegion.HOENN
            SINNOH_QUESTS.any { it.id == questId } -> TrainerRegion.SINNOH
            else -> null
        }
    }

    fun getChapterForQuest(quest: OsrsQuest): LeagueChapter? {
        val chId = quest.chapterId ?: return null
        val region = getRegionForQuest(quest.id) ?: return null
        return getChaptersForRegion(region).find { it.id == chId }
    }

    fun getTotemForQuest(questId: String): TotemInfo? {
        return (KANTO_BADGES + JOHTO_BADGES + HOENN_BADGES + SINNOH_BADGES).find {
            it.gymQuestId == questId || isQuestCompleted(it.gymQuestId, setOf(questId))
        }
    }

